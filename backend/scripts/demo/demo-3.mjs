// Requirement 3 demo: performance & caching, before vs after on the same code and data.
//   npm run demo:3
import {
  ACCOUNTS, after, answer, api, before, bold, compose, confirm, cyan, dim, login, ok, run, runScript, say, show, sleep, sql, step, table, title, waitApi, waitHealthy, preflight,
} from './lib.mjs';

let mode = 'after';
let replicaDelayed = false;
let admin;
let priceRestore;

/** Median of n sequential requests (no load): what one user feels. */
async function median(path, token, n = 7) {
  const times = [];
  for (let i = 0; i < n; i++) times.push((await api('GET', path, { token })).ms);
  return times.sort((a, b) => a - b)[Math.floor(n / 2)];
}

async function feel(label, adminToken, customerToken) {
  const rows = [
    ['dashboard statistics', await median('/orders/stats', adminToken)],
    ['admin: PENDING orders, page 3', await median('/orders?status=PENDING&limit=20&page=3', adminToken)],
    ['search "lamp"', await median('/products?search=lamp', undefined)],
    ['my orders (Ahmad, 3,000 orders)', await median('/orders?limit=20', customerToken)],
  ];
  return rows.map(([name, ms]) => [name, `${ms} ms`]);
}

function switchMode(to) {
  runScript('scripts/perf/mode.mjs', [to]);
  mode = to;
}

await run(
  async () => {
    await preflight();
    title('Requirement 3: performance & caching', 'Measure first, improve one thing, measure again. Four layers: database · Redis · HTTP · read replica');

    await step('Realistic data volume', 'With 5 orders everything is fast; slow queries only show up with real volume.');
    show('orders', Number(sql('orders_db', 'SELECT count(*) FROM orders')).toLocaleString());
    show('order items', Number(sql('orders_db', 'SELECT count(*) FROM order_items')).toLocaleString());
    show('products', Number(sql('products_db', 'SELECT count(*) FROM products')).toLocaleString());
    say(dim('(generated by npm run perf:data, removable with npm run perf:data -- --clean)'));

    // ───────── BEFORE ─────────
    await step('Switch to BEFORE: every optimisation off, old indexes back', 'Same code, PERF_MODE=before: no Redis, no ETag, no replica, old stats code, N+1 stock lookup.');
    switchMode('before');
    await waitApi();
    admin = await login(...ACCOUNTS.admin);
    const ahmad = await login(...ACCOUNTS.ahmad);

    await step('BEFORE: how the database reads (EXPLAIN ANALYZE)', 'Seq Scan = reads every row. Sort = an extra step a good index avoids.');
    runScript('scripts/perf/explain.mjs');

    await step('BEFORE: how long one request takes (no load, median of 7)', '');
    const feelBefore = await feel('before', admin.token, ahmad.token);
    table([['request', 'before'], ...feelBefore]);

    let loadTested = false;
    if (await confirm('Run the 30-second load test (50 users) in BEFORE mode?')) {
      await step('BEFORE: load test, 50 users for 30 s (k6)', 'p95 = 95% of requests are faster than this. requests/s = how much the system can serve.');
      runScript('scripts/perf/load-test.mjs', ['demo-before'], { DURATION: '30s' });
      loadTested = true;
    }

    // ───────── AFTER ─────────
    await step('Switch to AFTER: indexes, Redis, ETag, replica, SQL stats, one-call stock lookup', '');
    switchMode('after');
    await waitApi();

    await step('AFTER: EXPLAIN again', 'Index Scan = jumps straight to the rows it needs.');
    runScript('scripts/perf/explain.mjs');

    await step('AFTER: one request (no load, median of 7)', 'Before vs after, side by side.');
    const feelAfter = await feel('after', admin.token, ahmad.token);
    table([['request', 'before', 'after'], ...feelBefore.map(([name, ms], i) => [name, ms, feelAfter[i][1]])]);

    if (loadTested) {
      await step('AFTER: the same load test', '');
      runScript('scripts/perf/load-test.mjs', ['demo-after'], { DURATION: '30s' });
      await step('Before vs after under load', '');
      runScript('scripts/perf/compare.mjs', ['demo-before', 'demo-after']);
    } else {
      await step('Before vs after under load (saved 60 s runs)', 'Recorded earlier with the same test: 50 users, 60 s, 300k orders.');
      runScript('scripts/perf/compare.mjs', ['1-baseline', '2-indexes', '3-redis', '5-final-repeat']);
    }

    // ───────── Layers one by one ─────────
    await step('Redis: what is cached, and the hit rate', 'Cached: catalogue pages, products, categories, dashboard stats. Never: stock, private data, tokens.');
    const keys = compose(['exec', '-T', 'redis', 'redis-cli', '--scan', '--pattern', '*']).split('\n').filter(Boolean);
    show('keys in Redis', keys.length);
    keys.slice(0, 4).forEach((k) => say(dim(`  ${k.length > 90 ? `${k.slice(0, 90)}…` : k}`)));
    const [hits, misses] = compose(['exec', '-T', 'redis', 'redis-cli', 'MGET', 'stats:cache:hits', 'stats:cache:misses']).split('\n').map((n) => Number(n) || 0);
    show('cache hits / misses', `${hits} / ${misses}   (${((hits / (hits + misses || 1)) * 100).toFixed(1)}% served from memory)`);
    say(dim('  (counted since the switch to AFTER; the misses are the first load of each key)'));

    await step('An admin edit is visible immediately, despite Redis and the replica', 'The edit bumps the catalogue version (old cache unreachable) and reads go to the primary for 5 s.');
    const product = (await api('GET', '/products?search=Desk%20Lamp')).body.data[0];
    priceRestore = { id: product.id, price: product.price };
    await api('GET', `/products/${product.id}`); // make sure it is cached
    await api('PATCH', `/products/${product.id}`, { token: admin.token, body: { price: product.price + 1 } });
    const seen = (await api('GET', `/products/${product.id}`)).body.price;
    ok(seen === product.price + 1, `price was $${product.price}, admin set $${product.price + 1}, customer sees $${seen}`);
    await api('PATCH', `/products/${product.id}`, { token: admin.token, body: { price: product.price } });
    priceRestore = undefined;

    await step('ETag: do not send the same data twice', 'The client sends back the fingerprint; unchanged → 304 with no body. Saves network, not database.');
    const first = await api('GET', `/products/${product.id}`);
    const etag = first.headers.get('etag');
    const second = await api('GET', `/products/${product.id}`, { headers: { 'If-None-Match': etag } });
    await api('PATCH', `/products/${product.id}/stock`, { token: admin.token, body: { delta: -1 } });
    const changed = await api('GET', `/products/${product.id}`, { headers: { 'If-None-Match': etag } });
    await api('PATCH', `/products/${product.id}/stock`, { token: admin.token, body: { delta: 1 } });
    table([
      ['request', 'answer', 'bytes'],
      ['first time', answer(first), first.bytes],
      ['again, with If-None-Match', answer(second), second.bytes],
      ['after the stock changed', answer(changed), changed.bytes],
    ]);
    show('Cache-Control', `${first.headers.get('cache-control')}   ${dim('(orders, users: no-store)')}`);

    if (await confirm('Show the read replica + read-your-writes (delays the replica 3 s, about 30 s)?')) {
      await step('Read replica: a live read-only copy; reads go there, writes to the primary', 'The replica lags a little. We delay it 3 s on purpose so the lag is visible.');
      show('replication', sql('postgres', "SELECT application_name || ' · ' || state || ' · lag ' || coalesce(replay_lag::text, '0') FROM pg_stat_replication"));
      replicaDelayed = true;
      compose(['up', '-d', 'postgres-replica'], { REPLICA_DELAY_MS: '3000' });
      await waitHealthy('postgres-replica');
      await sleep(3000);
      runScript('scripts/perf/read-your-writes.mjs');
      compose(['up', '-d', 'postgres-replica'], { REPLICA_DELAY_MS: '0' });
      await waitHealthy('postgres-replica');
      replicaDelayed = false;
    }

    await step('Summary', '');
    table([
      ['', 'Before', 'After'],
      ['p95 (50 users)', '848 ms', '136 ms'],
      ['requests / second', '219', '652  (×3)'],
      ['admin orders (EXPLAIN)', '18 ms · Seq + Sort', '0.3 ms · Index Scan'],
      ['search (EXPLAIN)', '25 ms · Seq Scan', '0.3 ms · trigram index'],
      ['catalogue reads', 'database every time', 'Redis (~98% hits)'],
      ['unchanged product', 'full body again', '304 · 0 bytes'],
      ['reads', 'all on one database', 'replica (100%)'],
    ]);
    console.log(`\n${bold('  Done.')} ${cyan('System is back in AFTER mode.')}`);
  },
  async () => {
    if (priceRestore && admin) await api('PATCH', `/products/${priceRestore.id}`, { token: admin.token, body: { price: priceRestore.price } });
    if (replicaDelayed) {
      compose(['up', '-d', 'postgres-replica'], { REPLICA_DELAY_MS: '0' });
      await waitHealthy('postgres-replica');
    }
    if (mode !== 'after') {
      console.log(dim('\n  (putting the system back in AFTER mode...)'));
      runScript('scripts/perf/mode.mjs', ['after']);
    }
  },
);
